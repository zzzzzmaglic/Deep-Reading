评估情商
如今,很多大公司都聘请了训练有素的心理学家来开发出所谓的“能力模型”,以帮助他们
识别、培训和提拔潜在的领导人才。这些心理学家同样也针对基层岗位制定了相关模型。
近年来,我对188家公司的能力模型进行了深入分析,这些公司大都是规模庞大、业务遍
布全球的大公司,包括朗讯科技、英国航空和瑞信银行等知名公司。
在进行这项研究时,我的目标是识别出哪些个人技能能够真正帮助组织取得优秀表现,并
分析这些技能发挥作用的程度。
我把这些能力分成三类:一是纯粹的技术能力,比如会计和业务规划;二是认知能力,例
如分析性推理;三是情商能力,如团队协作和领导变革的能力。
