评估自己所做之事上投入了更多的精力。
换句话说,顶尖学生在他们的休息时间中应用了一些刻意练习的习惯——正念、观察自身
表现的能力、以及时间宝贵且需要明智使用的感觉。
他们发现了刻意休息的巨大价值。他们很早就意识到休息的重要性,我们在休息时完成了
