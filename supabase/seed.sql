高工作效率的事情”,并将这些数据与生产力进行了比较。这次,他们没有发现M形曲
线,而是发现了一个单一的曲线,其峰值出现在每天三到三个半小时左右。
遗憾的是,他们没有提及在办公室和家里总共投入的工作时间;他们仅仅暗示了“最有生
产力的研究者可能在家里或其他地方进行大部分创造性工作”的可能性,而不是在校园
里。如果假设这项研究中在办公室和家中最有生产力的工作者是同一群人,那么这个群体
每周的工作时间在25到38小时之间。按照六天工作周计算,平均每天工作四到六个小时。
在作家的生活中,我们也可以看到每天工作四到五个小时的类似规律。德国作家和诺贝尔
文学奖得主托马斯·曼到1910年时已经形成了固定的日常工作安排,那时他35岁,已经出
版了广受好评的小说《布登勃洛克家族》。
曼每天上午9点开始工作,他会把自己关在办公室,严令不得打扰,首先处理小说创作。
午餐后,他说:“下午是阅读、处理我那庞大的信件和散步的时间。”午睡一个小时和享用
下午茶后,他会再花一两个小时处理一些较为简单的短篇作品和编辑任务。
同样,19世纪伟大的英国小说家安东尼·特洛普也遵循着严格的写作时间表。在他1859年
至1871年居住在沃尔瑟姆庄园时期的生活记录中,他描述了自己成熟的工作模式。清晨5
点,随着仆人送来的咖啡,他首先回顾前一天的工作,然后在5:30准时将手表放在桌上开
始写作。他每小时写作1000字,平均每周完成40页稿子,直到早上8点去邮局的日常工
作。
以这种方式工作,他在1882年去世时,一生共出版了47部小说。尽管他很少表现出这是一
项了不起的成就,可能是因为他的母亲在50多岁开始写作以养家糊口,并出版了100多本
书。他写道:“我认为,所有作为文学家生活——每天都作为文学劳工工作的人——都会
同意我,每天三个小时的工作就能产出一个人应当创作的作品。”
特洛普稳定的工作时间与他的同代人查尔斯·狄更斯不谋而合。经历了早期的夜以继日的
劳作之后,狄更斯定下了一个“如同城市职员一般有条不紊”的工作时间表,他的儿子查理
如是说。狄更斯从早上9点一直工作到中午2点,期间休息吃午餐。他的大部分小说都是连
载在杂志上的,且狄更斯很少领先插画家和印刷商超过一两章。然而,五个小时的工作之
后,他便结束了一天的工作。
这种纪律性可能被视为维多利亚时期严格自律的一种体现,但许多20世纪的多产作者也遵
循了同样的工作方式。例如,埃及小说家纳吉布·马哈福兹,也是一位公务员,他主要在
下午4点到7点这段时间创作小说。加拿大作家爱丽丝·门罗,2013年诺贝尔文学奖得主,
她的写作时间是从早上8点持续到11点。澳大利亚小说家彼得·凯里表示:“我认为一天工
作 3 个小时就足够了”,这样的安排使他得以完成13部小说,包括两部获得布克奖的作
品。
W·萨默塞特·毛姆每天只工作四个小时,直到下午1点——“但从不少于此”,他强调道。加
夫列尔·加西亚·马尔克斯每天写作五个小时。欧内斯特·海明威则是在早上6点开始工作,
直到中午前结束。苏尔·贝娄除非面临截稿压力,通常会在早餐后开始写作,一直持续到
午餐时间,然后复查当天的成果。
爱尔兰小说家埃德娜·奥布莱恩会在上午工作,“大约在一两点停下,余下的下午时间处理
日常琐事”。斯蒂芬·金把每天四到六个小时的阅读和写作称作“紧张的一天”。
卡尔·安德斯·埃里克森、拉尔夫·克兰佩和克莱门斯·特施-罗默在20世纪80年代对柏林一所
音乐学院的小提琴学生进行的研究中观察到了类似的模式。
埃里克森、克兰佩和特施·罗默对区分杰出学生和一般学生的因素感兴趣。通过对音乐学
生及其老师的采访,以及让学生记录他们的时间安排,他们发现了几个因素将最优秀的学
生与其他学生区别开来。
首先,优秀的学生不仅仅是比一般学生练习得更多,更重要的是他们以更有意识、更专注
的方式进行练习。埃里克森解释说,在刻意练习过程中,你会“全神贯注地投入到一项特
定活动中,目的是为了提升自己的表现。”
你所做的不仅仅是重复练习、投掷球或演奏音阶。刻意练习是有目的、有结构的,它提供
了清晰的目标和反馈;这要求你专注于自己正在做的事情,并观察你如何能够做得更好。
当学生们对于如何达到卓越有一个清晰的路径时,他们就能够进行刻意练习,这个路径是
由对优秀作品和杰出作品,或者胜利者和失败者之间区别的共识所定义的。那些可以让人
实现最快时间、最高得分或最优雅解决方案的活动,都适合进行刻意练习。
其次,你需要有一个理由,让你日复一日地坚持下去。刻意练习并不总是有趣的,也不会
立即带来收益。这意味着你需要在日出之前就进入泳池,在你本可以和朋友一起出去玩的
时候练习挥杆或步伐,在没有窗户的房间里练习指法或呼吸技巧,花费数小时来完善那些
只有少数人会注意到的细节。
刻意练习本身并没有太多固有的或即时的乐趣,因此你需要有一个强烈的信念,相信这些
长时间的努力最终会得到回报,你不仅是在提升自己的职业前景,也在塑造自己的专业和
个人身份。你做这些不仅仅是为了金钱。你这么做是因为它强化了你对自己现在和将来身
份的认知。
刻意练习的概念以及埃里克森及其同事对世界级表演者练习总时长的测量受到了广泛的关
注。这项研究为马尔科姆·格拉德威尔提出的观点提供了基础——在他的书《异类:不一
样的成功启示录》(Outliers)中有详细论述——即成为世界级的高手需要10,000小时的练
习,而从国际象棋传奇人物鲍比·费舍尔到微软创始人比尔·盖茨再到披头士乐队,他们在
成名之前都已经投入了这些小时。
对于教练、音乐老师和有抱负的家长来说,这个数字似乎预示着通往NFL(美国国家橄榄
球联盟)、朱利亚德音乐学院或麻省理工学院的黄金大道:只需从小开始,保持忙碌,不
允许他们放弃。在一个将压力和过度工作视为美德而非弊端的文化中,10,000小时是一个
令人印象深刻的数字。
但是埃里克森及其同事在他们的研究中还注意到了一些几乎所有人都忽略掉的事情。他们
观察到,“刻意练习是一项需要付出努力的活动,每天只能持续有限的时间。”练习得太
少,你永远无法成为世界级的高手。
但是,如果练习过多,你就会增加受伤、精神耗尽或精疲力竭的风险。要想成功,学生必
须“避免筋疲力尽”并“将练习量限制在他们能够在每天或每周基础上完全恢复的数量内”。
最优秀的学生一般都遵循这样的模式:上午练习最刻苦、练习时间最
长,下午小睡一会儿,然后进行第二次练习。
那些被视为未来之星的学生是如何最大化利用有限的练习时间呢?他们的练习节奏呈现出
一种独特的模式。他们每周在练习室或运动场上投入的时间更多,但并不是通过增加每次
练习的时长来实现的。相反,他们采取了更频繁、时间更短的练习方式,每次练习大约持
续80到90分钟,每次之间休息半小时。
把这些练习时间累加起来,你会得到什么?大约每天四个小时。这和达尔文每天花在他最
艰苦的工作上的时间、哈代和利特尔伍德在数学上的投入时间、狄更斯和金在写作上的时
间几乎一样。即便是在世界顶级学校中雄心勃勃的年轻学生,为了准备一个竞争激烈的领
域,每天也只能承受四个小时的真正专注和严肃的努力。
埃里克森得出的结论是,这个上限“不是由可用时间决定的,而是由每天可用于刻意练习
的精神和体力资源决定的”。
学生们并不是仅仅练习四个小时就结束了一天的工作;讲座、排练、家庭作业以及其他事
务占据了他们一天中的其他时间。在采访中,学生们表示,“主要是他们维持刻意练习所
需的专注力的能力限制了他们的练习时间”。
这就是为什么需要十年时间来达到格拉德威尔提到的10000小时:如果你每天只能维持四
个小时的专注练习,那么每周练习20小时(假设周末休息),每年练习1000小时(假设有
两周假期)。
不仅音乐家的生活展示了刻意练习的重要性。雷·布拉德伯里从1932年开始认真地写作,
每天写1000字。“十年来,我每周至少完成一篇短篇小说”,他回忆说,但这些小说从未真
正成型。终于,在1942年,他写出了《湖》。多年后,他仍然记得那一刻。
“十年来我所做的一切错误,突然间变成了正确的想法、正确的场景、正确的人物、正确
的日子、正确的创作时机。我坐在户外,用打字机,在草坪上写这个故事。一个小时后,
故事完成了,我脖子后面的毛发都竖立了起来,我哭了。我知道我写出了我一生中第一个
真正好的故事。”
那些在柏林音乐学院被标记为优秀的学生,除了更多地练习外,他们还有一个几乎被完全
忽略的区别:他们如何休息。
