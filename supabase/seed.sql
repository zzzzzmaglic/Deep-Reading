此外,更进一步的分析表明,在公司高层,情商的作用愈加凸显,这里,技术能力的差异
基本可以忽略不计。这就是说,在组织中级别越高的人,情商在其成就中起到的作用就越
显著。在评估高级岗位上表现优秀的人和表现一般的人时,发现他们之间几乎90%的能力
差异来自于情商,而不是认知能力。
