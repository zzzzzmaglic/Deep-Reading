在卡尔·奥韦·克瑙斯高(Karl Ove Knausgaard)的自传体小说《我的奋斗》(My
Struggle)的第2432页,出现了一个关键情节:一部新的普鲁斯特(Proust)译著在挪
威出版了。
此时,克瑙斯高已近而立之年,他花了近十年的时间学习写作,然而,用“不成功”来形容
他的写作之路,已经是相当客气了。他最好的朋友,托雷·伦伯格(Tore Renberg),在
读过他的作品后,有一幕是这样的:伦伯格来到克瑙斯加德的公寓,看起来有些醉意,似
乎在来之前喝了点酒,想要壮胆。
“兄弟”,伦贝格思索良久终于鼓足勇气开了口,“你写的东西真的没人看”。
这已经不是我们第一次看到人们对克瑙斯高的作品做出这种评价的了。在这本书刚出版的
时候,他还在挪威北部一个偏远渔村当老师。他回家时发现同事们一边大声读着他写的性
爱场面,一边笑得前仰后合。还是处男的克瑙斯夸尔径直穿过厨房走进书房,一口气喝了
一整瓶酒,然后吐得书架上到处都是。
对于同事的嘲笑生气归生气,但克瑙斯高并没放到心里去。但伦贝格的批评可就扎心了,
因为这位比自己小几岁的伙伴彼时早已成为一位颇有成就的作家。所以伦贝格的评论就显
得那么权威又中肯,自己写的东西确实是无人问津的一滩烂泥。
于是,克瑙斯高干脆停笔不写了。当普鲁斯特的《追忆似水年华》的新译本出版时,他已
经两年没有写作了。在春日的阳光下,他一口气读完了普鲁斯特的七部回忆录,就像“喝
下一杯水”一样轻松,又感觉心灵深处的干涸得到了缓解。克瑙斯高形容这就像“回到很久
以前去过的森林......当你开始行走时,记忆就开始涌现”。
在那次顿悟之后......他又有两年的时间没有写作,本该完成的200页自传也没有写。
但是人生的转机总会在某一瞬间突然出现。出于某种科学无法解释的原因,挪威最大出版
社的一家子公司Tiden的一位编辑决定给克瑙斯高一份出版合同,尽管编辑自己都没把这
份合同当回事儿。
但是克瑙斯高却异常重视,他放弃了一切,搬回了母亲所在的小镇阿伦达尔
(Arendal),并开始着手创作他的处女作小说。一开始他并不知道该写些什么,只是无
意间在图书馆听到了一段对话记了下来,然后就从这里开始即兴发挥。
克瑙斯高的处女作讲述了 26 岁的教师亨里克·万克尔(Henrik Vankel)的故事。与许多
人的处女作一样,这本书感觉就像是克瑙斯高的自传——随着情节围绕着万克尔与他13岁
的学生米里亚姆(Miriam)在克瑙斯高曾经任教过的挪威北部一个相同的小渔村发生的
性关系展开,这种自传体的感觉变得更加强烈。同时,这本书一经出版就获得了评论界和
商业上的双重成功。
当我们试图探寻作品背后的故事时发现,这部作品的成功,很大一部分是因为其写作风格
完全是普鲁斯特式的。《出离世界》( Ude af verden)的每一句话都将普鲁斯特式敏感
表现得淋漓尽致,尤其是字里行间对时间和记忆的痴迷,如病毒般游走在行文间丰富而清
晰的语言。
虽然克瑙斯高极力否认自己作品的“普鲁斯特”化,但《追忆似水年华》中的某些东西已经
深深地影响了他,重新塑造了他的情感表达。在他没有写作的那两年里,他的写作风格发
生了翻天覆地的变化。
这种情况发生在作家身上很常见。当极具能量的文字遇上天性敏感的作家,作品的影响在
此刻达到了巅峰。如果有时作品的影响没有被内化为自己的东西,作家或许会怀疑自己的
感知能力是不是出了问题。但也没有其他办法,金科玉律就摆在那里:找到好的影响因素
是写好作品的前提。
有些作家天生不易被影响,但他们也会刻意去培养自己被影响的能力。维尔纳·赫尔佐格
(Werner Herzog)在写剧本之前,会花几天的时间阅读《诗经》,聆听外放至最大声
的古典音乐,从而让自己进入一种他称之为 “语言的陶醉”(ecstasy of language)的状
态。
正如我们在本系列第一部分所讨论的那样,约翰·弗鲁斯坎特(John Frusciante)在创作
歌曲时也会做类似的事情。
我们的大脑就是一种学习模型,上述行为就是让大脑获取大量的优质训练数据,这是一项
常常被忽视的重要技能。在学习一门新手艺时,你总在想我能做些什么,所以你阅读《风
